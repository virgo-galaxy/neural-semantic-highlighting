WORDS='aspen brook cypress delta elm forest glade heath island juniper kelp lotus mist north ocean pine quartz reed sage thyme'.split()
def main():
 root=PackSpec.open('ini').dataset_root/'sources/curriculum-v1';files={}
 from packs.ini.labeling.label import label
 for index,(family,template)in enumerate(TEMPLATES.items()):
  for variant in range(24):
   source=template.replace('@W@',WORDS[(index+variant)%len(WORDS)]).replace('@N@',str(random.Random(8686+index*101+variant).randrange(3,90)))+'\n'
   if variant%4==1:source=source.replace('\n','\r\n')
   if variant%13==3:source='\ufeff'+source
   label(source=source)
   raw=source.encode();p=root/family/f'{variant:02}.ini';p.parent.mkdir(parents=True,exist_ok=True)
   if p.exists()and p.read_bytes()!=raw:raise ValueError('Preserve previous INI task')
   if not p.exists():p.write_bytes(raw)
   files[str(p.relative_to(root))]=hashlib.sha256(raw).hexdigest()
 license=b'Original INI tasks authored for Neural Semantic Highlighting.\nPrivate development dataset; no upstream, Golden or display copies.\n';p=root/'LICENSE'
 if p.exists()and p.read_bytes()!=license:raise ValueError('Preserve original INI license')
 p.write_bytes(license);lock=dict(format='nsh-ini-curriculum-v1',generatorSha256=file_hash(Path(__file__)),families=len(TEMPLATES),files=files,licenseSha256=hashlib.sha256(license).hexdigest());p=root/'source.lock.json'
 if p.exists()and json.loads(p.read_text())!=lock:raise ValueError('Preserve original INI lock')
 p.write_text(json.dumps(lock,indent=2)+'\n');print(len(files),'files in',len(TEMPLATES),'families')
if __name__=='__main__':main()
